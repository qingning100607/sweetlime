private fun table(lang: AppLanguage): Map<String, String>? = when (lang) {
    AppLanguage.ZH -> null
    AppLanguage.EN -> EN
    AppLanguage.TW -> TW
}

/** 把一句简体原文翻译成当前语言。查不到就原样返回。 */
fun tr(zh: String): String = table(AppLocale.current)?.get(zh) ?: zh

/**
 * 模板串版：[pattern] 里的 `{}` 会按顺序被 [args] 顶掉。
 *
 * 先把 pattern 翻成目标语言（译文里的 `{}` 位置可以重排），再填参数，
 * 这样参数本身不用翻译、也不受语序影响。
 */
fun trf(pattern: String, vararg args: Any?): String {
    val text = tr(pattern)
    if (args.isEmpty()) return text
    val out = StringBuilder(text.length + 16)
    var i = 0
    var k = 0
    while (i < text.length) {
        if (k < args.size && text[i] == '{' && i + 1 < text.length && text[i + 1] == '}') {
            out.append(args[k]); k++; i += 2
        } else {
            out.append(text[i]); i++
        }
    }
    return out.toString()
}
